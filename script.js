const heroH1 = {
  es: 'Transformamos procesos en <em>soluciones inteligentes</em>.',
  en: 'We turn processes into <em>intelligent solutions</em>.'
};

function applyTranslations(lang){
  document.documentElement.lang = lang === 'en' ? 'en' : 'es-MX';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(translations[key]) el.innerHTML = translations[key][lang];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-i18n-placeholder');
    if(translations[key]) el.setAttribute('placeholder', translations[key][lang]);
  });
  const h1 = document.querySelector('[data-i18n-html="hero.h1"]');
  if(h1) h1.innerHTML = heroH1[lang];

  const esLabel = document.getElementById('langEs');
  const enLabel = document.getElementById('langEn');
  if(esLabel) esLabel.classList.toggle('active-lang', lang !== 'en');
  if(enLabel) enLabel.classList.toggle('active-lang', lang === 'en');
  localStorage.setItem('sakbeh_lang', lang);
}

function initLanguage(){
  const toggle = document.getElementById('langToggle');
  if(toggle){
    toggle.addEventListener('click', ()=>{
      const current = localStorage.getItem('sakbeh_lang') || 'es';
      applyTranslations(current === 'es' ? 'en' : 'es');
    });
  }
  const savedLang = localStorage.getItem('sakbeh_lang') || 'es';
  applyTranslations(savedLang);
}

function initQuoteForm(){
  const form = document.getElementById('quoteForm');
  if(!form) return;
  form.addEventListener('submit', function(e){
    e.preventDefault();
    const f = e.target;
    const lang = localStorage.getItem('sakbeh_lang') || 'es';
    const servicios = Array.from(f.querySelectorAll('input[name="servicios"]:checked')).map(cb=>cb.value).join(', ');
    const isEn = lang === 'en';
    const subject = (isEn ? 'Quote request - ' : 'Solicitud de cotización - ') + (f.empresa.value || '');
    const bodyLines = isEn ? [
      'Full name: ' + f.nombre.value,
      'Company: ' + f.empresa.value,
      'Email: ' + f.correo.value,
      'Phone: ' + (f.telefono.value || '-'),
      'Approx. users/teams: ' + (f.tamano.value || '-'),
      'Urgency: ' + (f.urgencia.value || '-'),
      'Services of interest: ' + (servicios || '-'),
      '',
      'Description of needs:',
      f.descripcion.value
    ] : [
      'Nombre completo: ' + f.nombre.value,
      'Empresa: ' + f.empresa.value,
      'Correo: ' + f.correo.value,
      'Teléfono: ' + (f.telefono.value || '-'),
      'No. aprox. de usuarios/equipos: ' + (f.tamano.value || '-'),
      'Urgencia: ' + (f.urgencia.value || '-'),
      'Servicios de interés: ' + (servicios || '-'),
      '',
      'Descripción de necesidades:',
      f.descripcion.value
    ];
    const mailto = 'mailto:contacto@sakbeh.mx?subject=' + encodeURIComponent(subject) + '&body=' + encodeURIComponent(bodyLines.join('\n'));
    window.location.href = mailto;
  });
}

document.addEventListener('DOMContentLoaded', function(){
  initLanguage();
  initQuoteForm();
});
